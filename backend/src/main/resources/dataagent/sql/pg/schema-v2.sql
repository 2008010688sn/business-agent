CREATE TRIGGER trg_data_agent_tenant_validate
BEFORE UPDATE OF tenant_id, deleted ON data_agent
FOR EACH ROW EXECUTE FUNCTION dataagent_validate_agent_tenant();

CREATE OR REPLACE FUNCTION dataagent_validate_datasource_tenant()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF EXISTS (
      SELECT 1
        FROM skill_datasource binding
       WHERE binding.datasource_id = OLD.id
         AND COALESCE(binding.deleted, false) = false
    ) OR EXISTS (
      SELECT 1
        FROM data_agent_skill_version version
       WHERE version.status IN ('PUBLISHED', 'RETIRED')
         AND COALESCE(version.deleted, false) = false
         AND version.datasource_config ->> 'datasourceId' = OLD.id::TEXT
    ) THEN
      RAISE EXCEPTION 'Datasource with active or published Skill references cannot be deleted, datasourceId=%', OLD.id;
    END IF;
    RETURN OLD;
  END IF;
  IF COALESCE(NEW.deleted, false) THEN
    IF EXISTS (
      SELECT 1
        FROM skill_datasource binding
       WHERE binding.datasource_id = NEW.id
         AND COALESCE(binding.deleted, false) = false
    ) OR EXISTS (
      SELECT 1
        FROM data_agent_skill_version version
       WHERE version.status IN ('PUBLISHED', 'RETIRED')
         AND COALESCE(version.deleted, false) = false
         AND version.datasource_config ->> 'datasourceId' = NEW.id::TEXT
    ) THEN
      RAISE EXCEPTION 'Datasource with active or published Skill references cannot be deleted, datasourceId=%', NEW.id;
    END IF;
    RETURN NEW;
  END IF;
  IF EXISTS (
    SELECT 1
      FROM skill_datasource binding
      JOIN data_agent_skill skill ON skill.id = binding.skill_id
     WHERE binding.datasource_id = NEW.id
       AND COALESCE(binding.deleted, false) = false
       AND COALESCE(skill.deleted, false) = false
       AND skill.tenant_id IS DISTINCT FROM NEW.tenant_id
  ) OR EXISTS (
    SELECT 1
      FROM data_agent_skill_version version
      JOIN data_agent_skill skill ON skill.id = version.skill_id
     WHERE version.status IN ('PUBLISHED', 'RETIRED')
       AND COALESCE(version.deleted, false) = false
       AND COALESCE(skill.deleted, false) = false
       AND version.datasource_config ->> 'datasourceId' = NEW.id::TEXT
       AND skill.tenant_id IS DISTINCT FROM NEW.tenant_id
  ) THEN
    RAISE EXCEPTION 'Datasource tenant cannot differ from its Skill bindings, datasourceId=%', NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_datasource_tenant_validate ON datasource;
CREATE TRIGGER trg_datasource_tenant_validate
BEFORE UPDATE OF tenant_id, deleted ON datasource
FOR EACH ROW EXECUTE FUNCTION dataagent_validate_datasource_tenant();

