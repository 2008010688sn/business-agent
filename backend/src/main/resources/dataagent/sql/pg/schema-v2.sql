-- Resource ownership is enforced in the database as well as in the service layer.
CREATE OR REPLACE FUNCTION dataagent_validate_agent_tenant()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF COALESCE(NEW.deleted, false) THEN
    RETURN NEW;
END IF;
  IF EXISTS (
    SELECT 1
      FROM data_agent_skill_binding binding
     WHERE binding.agent_id = NEW.id
       AND COALESCE(binding.deleted, false) = false
       AND binding.tenant_id IS DISTINCT FROM NEW.tenant_id
  ) THEN
    RAISE EXCEPTION 'Agent tenant cannot differ from an active Skill binding, agentId=%', NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

