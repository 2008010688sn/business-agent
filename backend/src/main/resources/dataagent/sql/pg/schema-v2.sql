CREATE OR REPLACE FUNCTION dataagent_validate_skill_datasource_ownership()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_skill_tenant VARCHAR(64);
  v_skill_scope VARCHAR(32);
  v_skill_kind VARCHAR(32);
  v_datasource_tenant VARCHAR(64);
BEGIN
  SELECT tenant_id, scope, skill_kind
    INTO v_skill_tenant, v_skill_scope, v_skill_kind
    FROM data_agent_skill
   WHERE id = NEW.skill_id AND deleted = false;
  IF NOT FOUND OR v_skill_scope <> 'TENANT' OR v_skill_tenant IS NULL THEN
    RAISE EXCEPTION 'Skill datasource must belong to an active tenant Skill, skillId=%', NEW.skill_id;
  END IF;

  SELECT tenant_id
    INTO v_datasource_tenant
    FROM datasource
   WHERE id = NEW.datasource_id AND deleted = false;
  IF NOT FOUND OR v_datasource_tenant <> v_skill_tenant THEN
    RAISE EXCEPTION 'Datasource tenant does not match Skill tenant, skillId=%, datasourceId=%',
      NEW.skill_id, NEW.datasource_id;
  END IF;

  IF COALESCE(NEW.is_active, false) AND v_skill_kind = 'QUERY' AND EXISTS (
    SELECT 1
      FROM skill_datasource existing
     WHERE existing.skill_id = NEW.skill_id
       AND existing.id <> COALESCE(NEW.id, -1)
       AND COALESCE(existing.is_active, false)
       AND COALESCE(existing.deleted, false) = false
  ) THEN
    RAISE EXCEPTION 'QUERY Skill can have only one active datasource, skillId=%', NEW.skill_id;
  END IF;
  RETURN NEW;
END;
$$;

