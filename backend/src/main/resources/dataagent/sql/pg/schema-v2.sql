CREATE OR REPLACE FUNCTION dataagent_validate_skill_version_ownership()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_skill_tenant VARCHAR(64);
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status IN ('PUBLISHED', 'RETIRED') THEN
      RAISE EXCEPTION 'Published Skill version cannot be deleted, versionId=%', OLD.id;
    END IF;
    RETURN OLD;
  END IF;
  IF NEW.skill_kind IS NULL
      OR NEW.execution_mode IS NULL
      OR NOT (
        (NEW.skill_kind = 'QA' AND NEW.execution_mode = 'KNOWLEDGE')
        OR (NEW.skill_kind = 'QUERY' AND NEW.execution_mode IN ('DETERMINISTIC', 'REACT'))
        OR (NEW.skill_kind IN ('ACTION', 'ORCHESTRATION') AND NEW.execution_mode = 'FLOW')
      ) THEN
    RAISE EXCEPTION 'Skill version kind/execution mode matrix is invalid, skillId=%, versionId=%',
      NEW.skill_id, NEW.id;
  END IF;
  SELECT tenant_id
    INTO v_skill_tenant
    FROM data_agent_skill
   WHERE id = NEW.skill_id
     AND COALESCE(deleted, false) = false;
  IF NOT FOUND OR NEW.tenant_id IS DISTINCT FROM v_skill_tenant THEN
    RAISE EXCEPTION 'Skill version tenant does not match its Skill, skillId=%, versionId=%', NEW.skill_id, NEW.id;
  END IF;

  IF TG_OP = 'UPDATE' AND OLD.status IN ('PUBLISHED', 'RETIRED') THEN
    IF NEW.status IS DISTINCT FROM OLD.status
        AND NOT (OLD.status = 'PUBLISHED' AND NEW.status = 'RETIRED') THEN
      RAISE EXCEPTION 'Published Skill version can only transition from PUBLISHED to RETIRED, versionId=%', OLD.id;
    END IF;
    IF NEW.deleted IS DISTINCT FROM OLD.deleted
        OR NEW.published_at IS DISTINCT FROM OLD.published_at
        OR NEW.published_by IS DISTINCT FROM OLD.published_by
        OR (
        NEW.skill_id IS DISTINCT FROM OLD.skill_id
        OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
        OR NEW.skill_kind IS DISTINCT FROM OLD.skill_kind
        OR NEW.execution_mode IS DISTINCT FROM OLD.execution_mode
        OR NEW.version_no IS DISTINCT FROM OLD.version_no
        OR NEW.skill_markdown IS DISTINCT FROM OLD.skill_markdown
        OR NEW.route_rules IS DISTINCT FROM OLD.route_rules
        OR NEW.knowledge_config IS DISTINCT FROM OLD.knowledge_config
        OR NEW.react_config IS DISTINCT FROM OLD.react_config
        OR NEW.flow_definition IS DISTINCT FROM OLD.flow_definition
        OR NEW.variables_schema IS DISTINCT FROM OLD.variables_schema
        OR NEW.flow_runtime_config IS DISTINCT FROM OLD.flow_runtime_config
        OR NEW.flow_policy_config IS DISTINCT FROM OLD.flow_policy_config
        OR NEW.resource_requirement IS DISTINCT FROM OLD.resource_requirement
        OR NEW.input_schema IS DISTINCT FROM OLD.input_schema
        OR NEW.output_schema IS DISTINCT FROM OLD.output_schema
        OR NEW.datasource_config IS DISTINCT FROM OLD.datasource_config
        OR NEW.semantic_config IS DISTINCT FROM OLD.semantic_config
        OR NEW.runtime_config IS DISTINCT FROM OLD.runtime_config
        OR NEW.checksum IS DISTINCT FROM OLD.checksum
      ) THEN
      RAISE EXCEPTION 'Published Skill version is immutable; create a new draft version, versionId=%', OLD.id;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

