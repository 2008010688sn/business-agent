CREATE SCHEMA IF NOT EXISTS v4_ai;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA public;

DO $$
DECLARE
  vector_schema TEXT;
BEGIN
  SELECT namespace.nspname
    INTO vector_schema
    FROM pg_extension extension
    JOIN pg_namespace namespace ON namespace.oid = extension.extnamespace
   WHERE extension.extname = 'vector';

  IF vector_schema IS NULL THEN
    CREATE EXTENSION vector WITH SCHEMA v4_ai;
  ELSIF vector_schema <> 'v4_ai' THEN
    ALTER EXTENSION vector SET SCHEMA v4_ai;
  END IF;
END;
$$;

SET search_path TO v4_ai, public;

