CREATE OR REPLACE FUNCTION dataagent_validate_skill_shape()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.scope <> 'TENANT' OR NEW.tenant_id IS NULL THEN
    RAISE EXCEPTION 'Skill must belong to a tenant, skillId=%', NEW.id;
  END IF;
  IF EXISTS (
    SELECT 1
      FROM data_agent_skill_version version
     WHERE version.skill_id = NEW.id
       AND version.tenant_id IS DISTINCT FROM NEW.tenant_id
  ) THEN
    RAISE EXCEPTION 'Skill tenant cannot differ from its versions, skillId=%', NEW.id;
  END IF;
  IF EXISTS (
    SELECT 1
      FROM data_agent_skill_binding binding
     WHERE binding.skill_id = NEW.id
       AND COALESCE(binding.deleted, false) = false
       AND binding.tenant_id IS DISTINCT FROM NEW.tenant_id
  ) THEN
    RAISE EXCEPTION 'Skill tenant cannot differ from its active bindings, skillId=%', NEW.id;
  END IF;
  IF NEW.skill_kind = 'QUERY' AND (
    SELECT count(*)
      FROM skill_datasource
     WHERE skill_id = NEW.id
       AND COALESCE(is_active, false)
       AND COALESCE(deleted, false) = false
  ) > 1 THEN
    RAISE EXCEPTION 'QUERY Skill can have only one active datasource, skillId=%', NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

